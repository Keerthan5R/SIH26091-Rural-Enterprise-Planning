import type { Language } from './types'

/** Selects a string by language, falling back to English when a Kannada value is missing. The
 *  report is narrated per language, so a section never mixes two languages. */
export function pick(language: Language, en: string, hi: string, kn?: string | null): string {
  if (language === 'hi') return hi
  if (language === 'kn' && kn) return kn
  return en
}

/** Selects a row from one of the small `{ en, hi, kn }` label tables by code. */
export function pickLabel(
  labels: Record<string, { en: string; hi: string; kn: string }>,
  code: string,
  language: Language,
): string {
  const entry = labels[code]
  if (!entry) return code
  if (language === 'hi') return entry.hi
  if (language === 'kn') return entry.kn
  return entry.en
}

export function inr(value: string | number | null | undefined): string {
  if (value === null || value === undefined) return '—'
  const n = Math.round(Number(value))
  if (!Number.isFinite(n)) return '—'
  const negative = n < 0
  const digits = String(Math.abs(n))
  let grouped = digits
  if (digits.length > 3) {
    const tail = digits.slice(-3)
    let head = digits.slice(0, -3)
    const parts: string[] = []
    while (head.length > 2) {
      parts.unshift(head.slice(-2))
      head = head.slice(0, -2)
    }
    if (head) parts.unshift(head)
    grouped = [...parts, tail].join(',')
  }
  return `${negative ? '-' : ''}₹${grouped}`
}

export function lakh(value: string | number): string {
  const n = Number(value)
  if (!Number.isFinite(n)) return '—'
  if (Math.abs(n) >= 1e7) return `₹${(n / 1e7).toFixed(2)} Cr`
  if (Math.abs(n) >= 1e5) return `₹${(n / 1e5).toFixed(2)} L`
  return inr(n)
}

/** The backend uses UNBOUNDED_DSCR = 999 as a sentinel for "no debt service in this year", which
 *  happens during a capitalized moratorium. It is not a coverage ratio, and printing "999.00" next
 *  to a real 1.50 norm invites a reader to conclude the loan is 600x safe than required. */
export const UNBOUNDED_DSCR = 999

export function isUnboundedDscr(value: string | number): boolean {
  return Number(value) >= UNBOUNDED_DSCR
}

export function ratio(value: string | number): string {
  return Number(value).toFixed(2)
}

/** Formats a DSCR for display, rendering the sentinel in words instead of as a number. */
export function dscr(value: string | number, strings: { noDebtService: string }): string {
  return isUnboundedDscr(value) ? strings.noDebtService : ratio(value)
}

export function pct(value: string | number, digits = 0): string {
  return `${(Number(value) * 100).toFixed(digits)}%`
}

